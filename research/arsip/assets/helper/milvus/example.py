from .milvus_helper import MilvusHelper


def example_basic_usage():
    """Basic usage example"""
    print("=== Example 1: Basic Usage ===\n")
    
    # Initialize from YAML config
    helper = MilvusHelper("config.yaml")
    
    # List collections (already created from config)
    collections = helper.list_collections()
    print(f"Collections: {collections}\n")
    
    # Insert data
    data = [
        {
            "id": "doc_001",
            "embedding": [0.1] * 768
        },
        {
            "id": "doc_002", 
            "embedding": [0.2] * 768
        },
        {
            "id": "doc_003",
            "embedding": [0.3] * 768
        }
    ]
    
    result = helper.insert("my_collection", data)
    print(f"Insert result: {result}\n")
    
    # Search
    query_vector = [0.15] * 768
    results = helper.search(
        collection_name="my_collection",
        query_vectors=[query_vector],
        anns_field="embedding",
        limit=5,
        output_fields=["id", "distance"]
    )
    
    print(f"Search results: {results}\n")


